# Estimate marginal density f_Y(y0)
# ------------------------------------------------------------

uy = (y0 - y) / hy

kernel_y = (
    1 / np.sqrt(2 * np.pi)
    * np.exp(-0.5 * uy**2)
)

f_y0 = kernel_y.sum() / (T * hy)

print("Estimated marginal density f_Y(y0):", f_y0)


# ------------------------------------------------------------
# Estimate joint density f_XY(x, y0)
# ------------------------------------------------------------

f_joint_y0 = []

for x0 in x_grid:

    ux = (x0 - x) / hx
    uy = (y0 - y) / hy

    kernel_x = (
        1 / np.sqrt(2 * np.pi)
        * np.exp(-0.5 * ux**2)
    )

    kernel_y = (
        1 / np.sqrt(2 * np.pi)
        * np.exp(-0.5 * uy**2)
    )

    density = (
        (kernel_x * kernel_y).sum()
        / (T * hx * hy)
    )

    f_joint_y0.append(density)


f_joint_y0 = np.array(f_joint_y0)


# ------------------------------------------------------------
# Conditional density
#
# f(X | Y = y0) = f(X,Y) / f_Y(y0)
# ------------------------------------------------------------

f_conditional = (
    f_joint_y0 / f_y0
)


