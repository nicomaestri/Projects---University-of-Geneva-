# Select two stocks
pair = returns.iloc[:, [0, 1]].dropna()

x = pair.iloc[:, 0]
y = pair.iloc[:, 1]

stock_x = pair.columns[0]
stock_y = pair.columns[1]

T = len(pair)

print("Stock X:", stock_x)
print("Stock Y:", stock_y)
print("Number of observations:", T)


# ------------------------------------------------------------
# Bandwidths
# ------------------------------------------------------------

sigma_x = x.std(ddof=0)
sigma_y = y.std(ddof=0)

# Rule of thumb for bivariate KDE
hx = sigma_x * T**(-1/6)
hy = sigma_y * T**(-1/6)

print("Bandwidth X:", hx)
print("Bandwidth Y:", hy)


# ------------------------------------------------------------
# Grids
# ------------------------------------------------------------

x_grid = np.linspace(
    x.min(),
    x.max(),
    100
)

y_grid = np.linspace(
    y.min(),
    y.max(),
    100
)


# ------------------------------------------------------------
# Estimate bivariate density
# ------------------------------------------------------------

f_xy = np.zeros(
    (len(y_grid), len(x_grid))
)

for i, y0 in enumerate(y_grid):

    for j, x0 in enumerate(x_grid):

        ux = (x0 - x) / hx
        uy = (y0 - y) / hy

        kernel_x = (
            1 / np.sqrt(2 * np.pi)
            * np.exp(-0.5 * ux**2)
        )

        kernel_y = (
            1 / np.sqrt(2 * np.pi)
            * np.exp(-0.5 * uy**2)
        )

        f_xy[i, j] = (
            (kernel_x * kernel_y).sum()
            / (T * hx * hy)
        )


# ------------------------------------------------------------
# Plot bivariate density
# ------------------------------------------------------------

X, Y = np.meshgrid(
    x_grid,
    y_grid
)

plt.figure(figsize=(10, 7))

contour = plt.contourf(
    X,
    Y,
    f_xy,
    levels=20
)

plt.xlabel(stock_x)
plt.ylabel(stock_y)

plt.title(
    f"Bivariate Gaussian Kernel Density\n"
    f"{stock_x} and {stock_y}"
)

plt.colorbar(
    contour,
    label="Density"
)

plt.tight_layout()
plt.show()


