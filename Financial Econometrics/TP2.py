# Divide the sample into two and estimate the densities

results_split = {}

for col in returns.columns:

    stock = returns[col].dropna()

    # Divide the sample into two
    T = len(stock)
    mid = T // 2

    first_half = stock.iloc[:mid]
    second_half = stock.iloc[mid:]

    # Common grid
    common_grid = np.linspace(
        stock.min(),
        stock.max(),
        500
    )

    # Rule-of-thumb bandwidths
    T1 = len(first_half)
    sigma1 = first_half.std(ddof=0)
    h1 = sigma1 * T1**(-1/5)

    T2 = len(second_half)
    sigma2 = second_half.std(ddof=0)
    h2 = sigma2 * T2**(-1/5)

    # Empty vectors
    f_first = []
    f_second = []

    # KDE estimation
    for x in common_grid:

        # First half
        u1 = (x - first_half) / h1

        kernel1 = (
            1 / np.sqrt(2 * np.pi)
            * np.exp(-0.5 * u1**2)
        )

        density1 = kernel1.sum() / (T1 * h1)
        f_first.append(density1)

        # Second half
        u2 = (x - second_half) / h2

        kernel2 = (
            1 / np.sqrt(2 * np.pi)
            * np.exp(-0.5 * u2**2)
        )

        density2 = kernel2.sum() / (T2 * h2)
        f_second.append(density2)

    # Store results
    results_split[col] = {
        "T": T,
        "T1": T1,
        "T2": T2,
        "h1": h1,
        "h2": h2,
        "grid": common_grid,
        "f_first": f_first,
        "f_second": f_second
    }

