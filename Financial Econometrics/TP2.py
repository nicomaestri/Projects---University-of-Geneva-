def kde_gaussian(obs, n_points, h=None):

    # Number of observations
    T = len(obs)

    # Rule of thumb if h is not specified
    if h is None:
        sigma_hat = obs.std(ddof=0)
        h = sigma_hat * T**(-1/5)

    # Grid
    x_grid = np.linspace(
        obs.min(),
        obs.max(),
        n_points
    )

    # Empty vector for estimated density
    f_hat = []

    # Evaluate the KDE at every point of the grid
    for x in x_grid:

        u = (x - obs) / h

        kernel = (
            1 / np.sqrt(2 * np.pi)
            * np.exp(-0.5 * u**2)
        )

        density = kernel.sum() / (T * h)

        f_hat.append(density)

    return x_grid, f_hat, h


